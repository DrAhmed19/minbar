/// تحويل التاريخ الميلادي إلى هجري (خوارزمية جدولية) + مناسبات منبر
({int y, int m, int d}) hijriOf(DateTime g) {
  final a = (14 - g.month) ~/ 12, yy = g.year + 4800 - a, mm = g.month + 12 * a - 3;
  final jd = g.day + (153 * mm + 2) ~/ 5 + 365 * yy + yy ~/ 4 - yy ~/ 100 + yy ~/ 400 - 32045;
  var l = jd - 1948440 + 10632;
  final n = (l - 1) ~/ 10631;
  l = l - 10631 * n + 354;
  final j = ((10985 - l) ~/ 5316) * ((50 * l) ~/ 17719) + (l ~/ 5670) * ((43 * l) ~/ 15238);
  l = l - ((30 - j) ~/ 15) * ((17719 * j) ~/ 50) - (j ~/ 16) * ((15238 * j) ~/ 43) + 29;
  final m = (24 * l) ~/ 709;
  final d = l - (709 * m) ~/ 24;
  return (y: 30 * n + j - 30, m: m, d: d);
}

class Occ {
  final String t;
  final List<String> k;
  const Occ(this.t, this.k);
}

const _ord = ['', 'الأولى', 'الثانية', 'الثالثة', 'الرابعة', 'الخامسة', 'السادسة', 'السابعة', 'الثامنة', 'التاسعة', 'العاشرة'];

Occ? occasionToday() {
  final h = hijriOf(DateTime.now());
  final m = h.m, d = h.d;
  if (m == 1 && d <= 9) return Occ('الليلة ${_ord[d + 1]} من محرم', ['محرم', 'الحسين', 'عاشوراء', 'كربلاء']);
  if (m == 1 && d == 10) return const Occ('يوم عاشوراء', ['عاشوراء', 'الحسين', 'كربلاء', 'محرم']);
  if (m == 1 && d <= 13) return const Occ('أيام محرم', ['محرم', 'الحسين', 'كربلاء']);
  if (m == 2 && d >= 15 && d <= 20) return Occ(d == 20 ? 'زيارة الأربعين' : 'أيام المسير إلى الأربعين', ['الأربعين', 'زيارة', 'مشاية', 'الحسين']);
  if (m == 2 && d >= 27) return const Occ('ذكرى وفاة النبي ﷺ والإمام الحسن', ['النبي', 'الحسن', 'المصطفى']);
  if ((m == 5 && d >= 12 && d <= 14) || (m == 6 && d >= 2 && d <= 3)) return const Occ('الأيام الفاطمية', ['فاطمة', 'الزهراء']);
  if (m == 9 && d >= 19 && d <= 21) return const Occ('ليالي القدر وشهادة الإمام علي', ['علي', 'أمير المؤمنين', 'الكوفة']);
  return null;
}

({String t, int d})? occasionNext() {
  const M = [
    [1, 1, 'محرم الحرام'],
    [2, 15, 'المسير إلى الأربعين'],
    [2, 20, 'زيارة الأربعين'],
    [2, 28, 'وفاة النبي ﷺ والإمام الحسن'],
    [5, 13, 'الأيام الفاطمية'],
    [6, 3, 'الأيام الفاطمية الثانية'],
    [9, 19, 'ليالي القدر وشهادة الإمام علي'],
  ];
  for (var i = 1; i <= 10; i++) {
    final h = hijriOf(DateTime.now().add(Duration(days: i)));
    for (final x in M) {
      if (x[0] == h.m && x[1] == h.d) return (t: x[2] as String, d: i);
    }
  }
  return null;
}
